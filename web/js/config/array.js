  // 每级增加的修炼速度 %（与丹药、修炼室等百分比相加）：第 n 级 = SPEED_INIT × SPEED_RATE^(n−1) × 这一级所在段的 SPEED_SEG
  SPEED_INIT: 0.3,     // 1 级的增加量
  SPEED_RATE: 1,       // 每级 × 这个倍率
