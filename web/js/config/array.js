  // 升到第 n 级需要的灵石：第 n 级 = COST_INIT × COST_RATE^(n−1) × 这一级所在段的 COST_SEG
  COST_INIT: 100,     // 1 级的灵石
  COST_RATE: 1.012,   // 每级 × 这个倍率
