window.CFG = window.CFG || {};

// 一次攻击伤害 = max(攻击 × MIN_DMG, 攻击 - 对方防御 × DEF_RATE) × 随机(RAND_MIN ~ RAND_MAX)
// 暴击时伤害 × CRIT_MULT。历练、试炼塔、雷劫都用这里。
CFG.battle = {
  MIN_DMG: 0.1,      // 保底伤害 = 攻击 × 0.1
  DEF_RATE: 0.5,     // 防御抵消比例
  RAND_MIN: 0.9,     // 伤害随机下限
  RAND_MAX: 1.1,     // 伤害随机上限
  CRIT_MULT: 2,      // 暴击倍率
  MAX_ROUNDS: 60,    // 一场战斗最多回合，超过算平手各自退去
  TOWER_HP_MIN: 0.3, // 气血低于上限这个比例不能挑战试炼塔
};
