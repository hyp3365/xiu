/* =====================================================================
 * ★ 数值设置 · 炼丹师 · 炼器师 · 灵植夫 ★
 * ---------------------------------------------------------------------
 * 改完把 index.html 里的 ?v=数字 加 1。
 *
 * 三种技艺都是 1 ~ 10 阶，一开始就是 1 阶；经验攒满 EXP[当前阶-1] 升一阶。
 * 获得经验：
 *   炼丹师 = 炼制的丹药枚数 × 丹阶 × dan.EXP_RATE（失败的那枚 × FAIL_EXP）
 *   炼器师 = 炼制的件数 × 物品阶 × qi.EXP_RATE（炉子、装备、法宝、戒指、空间石都算）
 *   灵植夫 = 收获的灵药株数 × 灵药品级 × ling.EXP_RATE（品级 = 灵药序号，青灵草 1、凝露花 2……）
 *
 * 炼丹 / 炼器成功率：
 *   基础成功率 = 技艺阶 ÷ 物品阶 ÷ RATE_DIV
 *     例：1 阶炼丹师炼一阶丹 = 1 ÷ 1 ÷ 2 = 50%；4 阶炼丹师炼二阶丹 = 4 ÷ 2 ÷ 2 = 100%
 *   成功率 = 基础成功率 × (1 + 宗门秘法「丹心 / 器心」%)，超过 100% 也只算 100%
 *   失败：材料照扣，什么也得不到（升阶装备失败时，上一阶装备退回背包）
 *
 * 灵植夫没有成功率，阶数越高：生长时间越短、收获越多（下面 ling 的两个数组）
 * ===================================================================== */
window.CFG = window.CFG || {};

CFG.craftsman = {
  MAX: 10,              // 最高阶
  // 升到下一阶需要的经验：依次是 1→2、2→3 …… 9→10
  EXP: [1000, 3000, 8000, 20000, 50000, 120000, 300000, 700000, 1500000],
  RATE_DIV: 2,          // 成功率公式里的「÷ 2」
  FAIL_EXP: 1,          // 炼制失败也给经验：× 这个倍率（0 = 失败不给经验）

  dan:  { name: "炼丹师", EXP_RATE: 1 },
  qi:   { name: "炼器师", EXP_RATE: 10 },
  ling: { name: "灵植夫", EXP_RATE: 0.2,
    // 1 ~ 10 阶：灵药生长时间减少 %
    GROW_CUT:  [0, 3, 6, 9, 12, 15, 18, 21, 24, 27],
    // 1 ~ 10 阶：收获数量增加 %
    YIELD_ADD: [0, 5, 10, 15, 20, 25, 30, 35, 40, 45],
  },
};
