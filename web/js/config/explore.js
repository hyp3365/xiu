/* =====================================================================
 * ★ 数值设置 · 历练 / 自动探索 ★
 * ---------------------------------------------------------------------
 * 所有数值文件都在 js/config/ 下，一个部分一个文件；改完把 index.html 里的 ?v=数字 加 1。
 * 写法：倍率 1.1 = 每次 ×1.1；概率 0.3 = 30%；时间单位见注释。
 *
 * 【一次探索的流程】（代码：js/modules/world.js 的 makePlan / exploreStep / exploreMs）
 *   一次走 TIME 步；事件顺序在出发时排好：
 *     普通怪 MONSTERS 个 + 精英怪 ELITES 个 + 灵药 随机(HERB_MIN~HERB_MAX) 次 + 矿脉 随机(ORE_MIN~ORE_MAX) 次，
 *     不足 (TIME − BOSS) 步的用「无事发生」补齐（超出的会被截掉），打乱顺序后，最后 BOSS 步固定是首领。
 *   每步耗时（秒）= max(STEP_MIN, STEP_SEC − 宗门秘法「神行」减少的秒数)
 *   每走一步恢复：气血 / 法力 + 上限 × (HEAL_STEP × 100 + 宗门秘法「斗血 / 斗灵」)%（战斗回合中不恢复）
 *   战败：本次探索立刻结束，遗失灵石 = 向下取整(身上灵石 × LOSE_STONE)
 *   气血低于上限 × STOP：不能开始历练 / 探索 / 秘境；自动探索每次结算后若低于它就自动停止
 *   怪物属性见 config/mobs.js；掉落（灵石、药材、矿石）全部在 config/drops.js
 *   秘境的步数、怪物数等用 config/mijing.js 自己的设置，但每步秒数、每步恢复、STOP 仍用这里的
 * ===================================================================== */
window.CFG = window.CFG || {};

/* ================= 五、历练 / 自动探索 ================= */
CFG.explore = {
  TIME: 100,         // 每次历练 / 自动探索走多少步
  STEP_SEC: 3,       // 每走一步的秒数（宗门秘法「神行」可减少）
  STEP_MIN: 0.1,     // 每步最少秒数（「神行」减到这里为止）
  STOP: 0.3,         // 气血低于上限这个比例（0.3 = 30%）就不能出发 / 自动探索停止
  HEAL_STEP: 0,      // 每走一步恢复气血、法力上限的比例（0.02 = 每步 2%；0 = 只靠宗门秘法恢复）
  // 每次探索固定遇到的事件数量（其余步数无事发生，顺序随机）：
  MONSTERS: 10,      // 普通怪个数
  ELITES: 3,         // 精英怪个数
  BOSS: 1,           // 首领个数（放在最后几步）
  HERB_MIN: 5,       // 发现灵药次数下限
  HERB_MAX: 10,      // 发现灵药次数上限
  ORE_MIN: 5,        // 发现矿脉次数下限
  ORE_MAX: 10,       // 发现矿脉次数上限
  LOSE_STONE: 0.1,   // 战败遗失身上灵石的比例（0.1 = 10%）
};
