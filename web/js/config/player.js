/* =====================================================================
 * ★ 数值设置 · 人物属性 ★
 * ---------------------------------------------------------------------
 * 所有数值文件都在 js/config/ 下，一个部分一个文件；改完把 index.html 里的 ?v=数字 加 1。
 * 写法：倍率 1.1 = 每次 ×1.1；概率 0.3 = 30%；时间单位见注释。
 *
 * 【境界成长倍率】f = GROW ^ L（L = 总层序：练气一层 0，练气十层 9，筑基一层 10……，凡人按 0 算）
 *
 * 【最终属性】（js/modules/player.js 的 computeStats）
 *   生命上限 = (base.hp × f + 装备 + 功法 + 属性丹/肉身/自定义物品) × (1 + 装备生命% / 100)
 *   攻击 / 防御 / 法力上限 / 命中 / 闪避 = base.xxx × f + 装备 + 功法 + 属性丹/肉身/自定义物品
 *   速度 = base.speed × f + 装备 + 肉身 + 丹药 + 自定义物品
 *   暴击% = min(CRIT_CAP, fixed.crit + 装备 + 属性丹/肉身/自定义物品)（不随境界成长）
 *   境界修炼速度 = base.cultivate × f
 *     → 基础修炼速度 = 境界修炼速度 + 秘诀（功法）+ 宗门秘法「聚元」
 *     → 总修炼速度 = 基础修炼速度 × (1 + (聚灵阵% + 丹药% + 修炼室%) / 100)（百分比先相加再乘一次）
 *   每系抗性 = RES_BASE × f + 本系真诀（功法）+ 装备 + 肉身 + 丹药 + 自定义物品
 *
 * 例：筑基一层（L=10）攻击 = 3.6 × 1.08^10 ≈ 7.8（再加装备、功法等）
 * 雷劫、怪物属性也按这里的 base × f 生成（见 js/data/refstats.js），改 base / GROW 会一起变。
 * ===================================================================== */
window.CFG = window.CFG || {};

/* ================= 二、人物属性 ================= */
CFG.player = {
  GROW: 1.08,         // 每升一层（小境界也算），base 里的属性都 × 这个倍率：属性 = base × GROW^L
  base: {             // 练气一层时的数值（随境界成长 × GROW^L）；开局生命、法力也取这里
    hp: 64.2,           // 生命上限
    atk: 3.6,           // 攻击
    def: 3.6,           // 防御
    mana: 67.4,          // 法力上限
    speed: 3.4,         // 速度（决定先手）
    hit: 3.4,           // 命中（对抗对方闪避）
    dodge: 3.4,         // 闪避（对抗对方命中）
    cultivate: 1,     // 境界修炼速度（每 10 秒获得的修为 / 消耗的灵气，加成前）
  },
  fixed: {            // 不随境界成长（靠功法、装备、丹药提升）
    crit: 5,          // 暴击率 %（暴击伤害倍率见 config/battle.js 的 CRIT_MULT）
  },
  // 闪避几率 % = (防守方闪避 − 进攻方命中) ÷ 进攻方命中 × 100 ÷ DODGE_DIV，最低 0，最高 DODGE_CAP
  //   例：闪避比对方命中高 38%，几率 = 38 ÷ 38 = 1%……高 100% 时约 2.6%
  //   （命中、闪避都随境界成长，所以按比例算；闪避不高于对方命中就是 0）
  DODGE_DIV: 38,      // 闪避换算除数：越大闪避越难触发
  DODGE_CAP: 40,      // 闪避几率上限 %
  CRIT_CAP: 30,       // 暴击率上限 %
  // 平时恢复：每 10 秒恢复上限的百分之几（宗门秘法会再加）
  //   战斗回合中不恢复；历练/探索每走一步恢复 config/explore.js 的 HEAL_STEP + 宗门秘法「斗灵 / 斗血」
  REGEN_IDLE:   {
    hp: 1,            // 每 10 秒恢复 生命上限 × 1%
    mana: 1,          // 每 10 秒恢复 法力上限 × 1%
  },
};

// ---------- 六系抗性（金 木 水 火 土 雷） ----------
// 每系抗性 = RES_BASE × GROW^L + 本系真诀（功法）+ 装备 + 肉身 + 丹药 + 自定义物品
// 被某系法术打中时（js/modules/world.js）：
//   伤害 = 法术威力 × 灵根法术加成 − (防御 × 战斗.RES_RATE + 该系抗性) × 战斗.DEF_RATE（最低 攻击 × 战斗.MIN_DMG）
//   （RES_RATE、DEF_RATE 在 config/battle.js；普通攻击、法宝只算防御）
CFG.player.RES_BASE = 3.4;   // 练气一层时每系抗性（随境界 × GROW^L）
