/* =====================================================================
 * ★ 数值设置 · 人物属性 ★
 * ---------------------------------------------------------------------
 * 所有数值文件都在 js/config/ 下，一个部分一个文件；改完把 index.html 里的 ?v=数字 加 1。
 * 写法：倍率 1.1 = 每次 ×1.1；概率 0.3 = 30%；时间单位见注释。
 * ===================================================================== */
window.CFG = window.CFG || {};

/* ================= 二、人物属性 ================= */
CFG.player = {
  GROW: 1.12,         // 每升一层，下面 base 里的属性都 × 这个倍率
  base: {            // 练气一层时的数值（随境界成长）
    hp: 30,         // 气血上限
    atk: 10,         // 攻击
    def: 11,          // 防御
    mana: 5,        // 法力上限
    speed: 5,       // 速度（先手）
    hit: 6,         // 命中
    dodge: 5,       // 闪避
    cultivate: 3,   // 基础修炼速度（每 10 秒）
  },
  fixed: {           // 不随境界成长（靠功法、装备、丹药提升）
    crit: 5,         // 暴击 %
  },
  // 闪避几率 % = (防守方闪避 - 进攻方命中) ÷ 进攻方命中 × 100 ÷ DODGE_DIV
  //   例：闪避比对方命中高 20%，几率 = 20 ÷ 2 = 10%（命中、闪避都随境界成长，所以按比例算）
  DODGE_DIV: 38,
  DODGE_CAP: 40,     // 闪避几率上限 %
  CRIT_CAP: 30,      // 暴击上限 %
  REGEN: 0.01,       // 气血、法力每 10 秒恢复上限的比例
};

// ---------- 六系抗性（金 木 水 火 土 雷） ----------
// 每系抗性 = RES_BASE × 成长倍率^层序 + 本系真诀（功法）
// 被法术打中时：伤害 = 法术威力 - (防御 + 对应属性抗性) × 战斗.DEF_RATE
CFG.player.RES_BASE = 4;   // 练气一层时每系抗性
