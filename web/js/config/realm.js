/* =====================================================================
 * ★ 数值设置 · 境界 & 修为 ★
 * ---------------------------------------------------------------------
 * 所有数值文件都在 js/config/ 下，一个部分一个文件；改完把 index.html 里的 ?v=数字 加 1。
 * 写法：倍率 1.1 = 每次 ×1.1；概率 0.3 = 30%；时间单位见注释。
 *
 * 【总层序 L】24 个大境界 × 每境界 10 层，L = 大境界序号 × 10 + 层(0~9)
 *   例：练气一层 L=0，练气十层 L=9，筑基一层 L=10，筑基三层 L=12 …… 大道圣人十层 L=239
 *   大境界顺序见 js/data/realms.js 的 DATA.realms（练气 筑基 金丹 …… 天道圣人 大道圣人）
 *
 * 【修为需求】（js/data/realms.js 的 DATA.needExp）
 *   凡人 → 练气一层           = MORTAL_EXP
 *   第 L 层 → 第 L+1 层       = FIRST_EXP × EXP_RATE ^ L
 *   例：练气一层→二层 = 1500；练气十层→筑基一层（L=9）= 1500 × 1.386^9 ≈ 2.8 万
 *   突破成功后扣掉这一层需要的修为，多出来的修为保留。
 *
 * 【突破】凡人 → 练气、练气期内的小境界：修为够了直接突破
 *   需要渡雷劫的突破（见 config/trib.js 的 START）：撑过雷劫才算突破成功
 * ===================================================================== */
window.CFG = window.CFG || {};

/* ================= 一、境界 & 修为 ================= */
CFG.realm = {
  MORTAL_EXP: 500,      // 凡人 → 练气一层 需要的修为
  FIRST_EXP: 1500,      // 练气一层 → 二层 需要的修为（L=0 那一层的需求）
  EXP_RATE: 1.386,      // 每往上一层，需要的修为 × 这个倍率（第 L 层需求 = FIRST_EXP × EXP_RATE^L）
};
