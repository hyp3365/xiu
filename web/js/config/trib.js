/* =====================================================================
 * ★ 数值设置 · 雷劫 ★
 * ---------------------------------------------------------------------
 * 所有数值文件都在 js/config/ 下，一个部分一个文件；改完把 index.html 里的 ?v=数字 加 1。
 * 写法：倍率 1.1 = 每次 ×1.1；概率 0.3 = 30%；时间单位见注释。
 *
 * 【什么时候渡劫】突破后的总层序 ≥ START 时，每一层突破都要渡雷劫（不再看成功率）
 *   总层序 L = 大境界序号 × 10 + 层(0~9)：练气一层 0 …… 练气十层 9，筑基一层 10
 *
 * 【雷劫属性】（js/modules/cultivate.js 的 makeTrib，js/data/refstats.js 的 DATA.refStats）
 *   参考属性 = 突破后那一层的人物属性（config/player.js 的 base × GROW^L）
 *              + 该境界能学的全部宗门功法都练到第 GF 层的加成（不算丹药、肉身、灵根、装备）
 *   雷劫气血 = 参考气血 × MULT.hp；攻击 = 参考攻击 × MULT.atk；防御 = 参考防御 × MULT.def
 *   雷劫暴击率 = crit %
 *
 * 【战斗过程】每 config/battle.js 的 ROUND_SEC 秒（默认 2 秒）一回合：
 *   人物先打雷劫，雷劫没散再劈人物；双方都不计闪避，都能暴击；渡劫中不恢复气血、法力
 *   一次伤害 = max(攻击 × MIN_DMG, 攻击 − 对方防御 × DEF_RATE) × 随机(RAND_MIN ~ RAND_MAX)，暴击 × CRIT_MULT
 *   TIME 秒内打掉雷劫全部气血、自己没倒 = 突破成功
 *   自己气血打空 或 时间到 = 失败：气血剩 1，损失 当前修为 × FAIL_LOSS（向下取整）
 * ===================================================================== */
window.CFG = window.CFG || {};

/* ================= 十二、雷劫（突破时） ================= */
CFG.trib = {
  START: 10,          // 突破后总层序 ≥ 10 要渡劫：10 = 突破到筑基期一层（练气期是 0~9），之后每层都有雷劫
  TIME: 600,          // 渡劫时限（秒）
  FAIL_LOSS: 0.05,    // 渡劫失败损失当前修为的比例，0.05 = 5%
  GF: 4,              // 参考属性里，全部宗门功法按练到第几层计算（0 = 不算功法）
  MULT: {             // 雷劫属性 = 参考属性 × 下面的倍率（不写某项 = 1）
    hp: 1,            // 雷劫气血倍率
    atk: 1,           // 雷劫攻击倍率
    def: 1,           // 雷劫防御倍率
  },
  crit: 5,            // 雷劫暴击率 %
};
