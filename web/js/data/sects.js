DATA.sects = [];
DATA.sectById = {};
SECT_NAMES.forEach((list, i) => {
  const star = i + 1;
  list.forEach(([prefix, name], j) => {
    const sect = {
      id: `s${star}_${j}`, star, prefix, name,
      reqRealm: (star - 1) * 2,
      taskContrib: 10 * star,       // 每次宗门任务获得的贡献
    };
    DATA.sects.push(sect);
    DATA.sectById[sect.id] = sect;
  });
});

